-- ════════════════════════════════════════════════════════════════════
--  บังคับเปลี่ยน PIN ตั้งต้น และแยกผู้ดูแลระบบออกจากคุณวุฒิพยาบาล
--
--  บัญชี N001-N015 และ A001-A010 ถูกสร้างพร้อมกันด้วย PIN ตั้งต้นชุดเดียว
--  ตราบใดที่ยังไม่เปลี่ยน ใครก็เข้าบัญชีของคนอื่นได้ และ audit log
--  จะชี้ตัวผู้บันทึกไม่ได้จริง จึงตั้งธงบังคับเปลี่ยนก่อนใช้งานครั้งแรก
--
--  บัญชีเดิม AD01 AU01 H001 IC01 ไม่ตั้งธง เพราะใช้ PIN ส่วนตัวอยู่แล้ว
-- ════════════════════════════════════════════════════════════════════

alter table app_user
  add column if not exists must_change_pin boolean not null default false,
  add column if not exists pin_changed_at  timestamptz;

comment on column app_user.must_change_pin is
  'ต้องตั้ง PIN ใหม่ก่อนใช้งาน — ตั้งเมื่อสร้างบัญชีใหม่หรือเมื่อแอดมินรีเซ็ต PIN ให้';
comment on column app_user.pin_changed_at is
  'เวลาที่เจ้าของบัญชีตั้ง PIN เอง — null คือยังใช้ PIN ที่ระบบหรือแอดมินตั้งให้';

update app_user
set must_change_pin = true
where employee_id ~ '^[NA][0-9]{3}$'
  and pin_changed_at is null;

-- ────────────────────────────────────────────────────────────────────
--  ผู้ดูแลระบบไม่ใช่บุคลากรพยาบาล
--
--  0012 ตั้ง AD01 เป็น RN ไว้เพื่อให้ประเมินได้โดยไม่ต้องเลือกทุกเวร
--  แต่นั่นทำให้การประเมินของแอดมินถูกนับรวมในสถิติ RN ซึ่งไม่จริง
--  ถอดคุณวุฒิออก แล้วให้โค้ดยกเว้น role ADMIN จากการต้องเลือก RN/NA แทน
-- ────────────────────────────────────────────────────────────────────

update app_user
set nurse_level = null
where employee_id = 'AD01'
  and role = 'ADMIN';

-- ════════════════════════════════════════════════════════════════════
--  ระดับผู้ประเมิน RN / PN
--
--  บันทึกแยกจาก role ในระบบ เพราะ role บอกสิทธิ์การใช้งาน
--  ส่วน RN/PN คือคุณวุฒิของผู้ที่ลงมือประเมินจริง ซึ่งงานวิจัยใช้เปรียบเทียบ
--  ความสอดคล้องของการปฏิบัติตาม bundle ระหว่างสองกลุ่ม
--
--  เปิดให้ว่างได้ เพราะแถวที่บันทึกไว้ก่อนหน้านี้ยังไม่มีค่า
--  และรายการที่ค้างอยู่ในคิวออฟไลน์ของเครื่องผู้ใช้ก็ยังไม่มีเช่นกัน
-- ════════════════════════════════════════════════════════════════════

create type nurse_level as enum ('RN', 'PN');

alter table assessment add column nurse_level nurse_level;

comment on column assessment.nurse_level is
  'คุณวุฒิของผู้ประเมิน RN = พยาบาลวิชาชีพ, PN = ผู้ช่วยพยาบาล';

create index assessment_nurse_level_idx on assessment(nurse_level);
